#!/usr/bin/env node
// Regenerate lib/manifest.js for an Etude tag and a Node 24 release.
// Usage: node scripts/manifest-from-tag.mjs v3.1.2 v24.22.2
// Reads Etude's package-lock.json at that tag from GitHub and keeps only the packages the CLI
// imports (and their dependencies). Hashes the source tarball while streaming it.
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const [tag, nodeTag] = process.argv.slice(2)
if (!/^v\d+\.\d+\.\d+$/.test(tag || '') || !/^v24\.\d+\.\d+$/.test(nodeTag || '')) {
  console.error('usage: manifest-from-tag.mjs <etude tag vX.Y.Z> <node tag v24.X.Y>')
  process.exit(2)
}
// The packages src/core and src/cli import outside node:* (checked with grep at 3.1.2;
// unpdf, sqlite-wasm and @hono/node-server are imported lazily by commands the tool denies or
// by the browser build).
const ROOTS = ['marked', 'ts-fsrs', 'hash-wasm', 'quickjs-emscripten']

async function sha256(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
  const h = createHash('sha256')
  for await (const chunk of res.body) h.update(chunk)
  return h.digest('hex')
}

const lock = await (await fetch(`https://raw.githubusercontent.com/Zibhelina/etude/${tag}/package-lock.json`)).json()
const pkgs = lock.packages
const seen = new Set()
const packages = []
function walk(name) {
  if (seen.has(name)) return
  seen.add(name)
  const e = pkgs[`node_modules/${name}`]
  if (!e) throw new Error(`${name} missing from the lockfile`)
  packages.push({ name, version: e.version, url: e.resolved, integrity: e.integrity })
  for (const d of Object.keys(e.dependencies || {})) walk(d)
}
ROOTS.forEach(walk)

const sums = await (await fetch(`https://nodejs.org/dist/${nodeTag}/SHASUMS256.txt`)).text()
const builds = {}
for (const arch of ['x64', 'arm64']) {
  const file = `node-${nodeTag}-linux-${arch}.tar.gz`
  const line = sums.split('\n').find((l) => l.endsWith(`  ${file}`))
  if (!line) throw new Error(`no checksum for ${file}`)
  builds[arch] = { url: `https://nodejs.org/dist/${nodeTag}/${file}`, sha256: line.split(/\s+/)[0] }
}

const etudeUrl = `https://codeload.github.com/Zibhelina/etude/tar.gz/refs/tags/${tag}`
const manifest = {
  etude: { version: tag.slice(1), tag, url: etudeUrl, sha256: await sha256(etudeUrl) },
  node: { version: nodeTag.slice(1), builds },
  packages,
}
const out = fileURLToPath(new URL('../lib/manifest.js', import.meta.url))
writeFileSync(
  out,
  '// Pinned Etude runtime. Generated by scripts/manifest-from-tag.mjs; edit by regenerating.\n' +
    '// Keep etude.version equal to etude.ref in etude-cloudflare (the version its Sync server is tested against).\n\n' +
    `export const MANIFEST = ${JSON.stringify(manifest, null, 2)}\n`,
)
console.log(`wrote ${out}: etude ${tag}, node ${nodeTag}, ${packages.length} packages`)
